// Generates supabase/seed.sql from demo/demo-business.json, so the demo
// website (offline mode) and the database demo share one source of truth.
// Usage: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const b = JSON.parse(readFileSync(join(root, "demo/demo-business.json"), "utf8"));

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v) => `${q(JSON.stringify(v ?? {}))}::jsonb`;

const lines = [
  "-- AUTO-GENERATED by scripts/build-seed.mjs from demo/demo-business.json. Do not edit by hand.",
  "-- Creates the fictional demo business used on faidahq.com/demo/.",
  "-- Safe to re-run: it replaces only the demo business's knowledge items.",
  "",
  `insert into public.businesses (id, slug, name, type, description, email, phone, whatsapp, website, address, city, country, timezone, currency, branding, status, plan_code)`,
  `values (${[b.id, b.slug, b.name, b.type, b.description, b.email, b.phone, b.whatsapp, b.website, b.address, b.city, b.country, b.timezone, b.currency].map(q).join(", ")}, ${j(b.branding)}, 'active', 'growth')`,
  `on conflict (id) do update set name = excluded.name, description = excluded.description, branding = excluded.branding,`,
  `  email = excluded.email, phone = excluded.phone, whatsapp = excluded.whatsapp, website = excluded.website,`,
  `  address = excluded.address, city = excluded.city, country = excluded.country;`,
  "",
  `insert into public.ai_settings (business_id, tone, extra_instructions) values (${q(b.id)}, ${q(b.ai_settings?.tone)}, ${q(b.ai_settings?.extra_instructions ?? "")})`,
  `on conflict (business_id) do update set tone = excluded.tone, extra_instructions = excluded.extra_instructions;`,
  "",
  `delete from public.knowledge_items where business_id = ${q(b.id)};`,
  `insert into public.knowledge_items (business_id, category, title, content, price, price_unit, metadata, sort_order) values`,
  b.knowledge.map((k, i) =>
    `  (${q(b.id)}, ${q(k.category)}, ${q(k.title)}, ${q(k.content)}, ${k.price ?? "null"}, ${q(k.price_unit)}, ${j(k.metadata)}, ${i})`
  ).join(",\n") + ";",
  "",
];
writeFileSync(join(root, "supabase/seed.sql"), lines.join("\n"));
console.log(`Wrote supabase/seed.sql (${b.knowledge.length} knowledge items)`);
